/* Compile-time policy checks, NOT execution of the MCU or RTOS.
 * Expected observations are independent scenarios, including stop/fault edges. */
#include "axis_status.h"
#define CHECK(name, condition) typedef char check_##name[(condition) ? 1 : -1]
#define STATE(enabled, aligning, inhibits)     AXIS_STATUS_STATE(AXIS_STATUS_NEXT(0U, enabled, aligning, inhibits))
CHECK(word_32_bits, sizeof(uint32_t) == 4U);
CHECK(boot_zero, AXIS_STATUS_PACK(AXIS_OBS_BOOT, 0U) == 0U);
CHECK(initial_offsets, STATE(0U, 1U, AXIS_INHIBIT_CURRENT_OFFSETS) == AXIS_OBS_CALIBRATING);
CHECK(idle_not_aligning, STATE(0U, 1U, 0U) == AXIS_OBS_IDLE);
CHECK(idle_ready, STATE(0U, 0U, 0U) == AXIS_OBS_IDLE);
CHECK(align_when_enabled, STATE(1U, 1U, 0U) == AXIS_OBS_ALIGNING);
CHECK(run_when_enabled, STATE(1U, 0U, 0U) == AXIS_OBS_RUNNING);
CHECK(disabled_is_idle, STATE(0U, 1U, AXIS_INHIBIT_POWER_DISABLED) == AXIS_OBS_IDLE);
CHECK(prepared_wait_is_idle, STATE(0U, 1U, AXIS_INHIBIT_PWM_NOT_PREPARED) == AXIS_OBS_IDLE);
CHECK(feedback_wait_is_idle, STATE(0U, 0U, AXIS_INHIBIT_SPEED) == AXIS_OBS_IDLE);
CHECK(stop_from_run, AXIS_STATUS_STATE(AXIS_STATUS_NEXT(
    AXIS_STATUS_PACK(AXIS_OBS_RUNNING, 0U), 0U, 1U, 0U)) == AXIS_OBS_IDLE);
CHECK(fault_over_alignment, STATE(1U, 1U, AXIS_INHIBIT_FAULT) == AXIS_OBS_FAULT);
CHECK(fault_over_running, STATE(1U, 0U, AXIS_INHIBIT_FAULT) == AXIS_OBS_FAULT);
CHECK(fault_over_offsets, STATE(0U, 1U,
    AXIS_INHIBIT_FAULT | AXIS_INHIBIT_CURRENT_OFFSETS) == AXIS_OBS_FAULT);
CHECK(fault_over_idle, STATE(0U, 0U, AXIS_INHIBIT_FAULT) == AXIS_OBS_FAULT);
CHECK(latch_boot, AXIS_STATUS_STATE(AXIS_STATUS_ON_FAULT(AXIS_OBS_BOOT)) == AXIS_OBS_FAULT);
CHECK(latch_calibrating, AXIS_STATUS_STATE(AXIS_STATUS_ON_FAULT(AXIS_OBS_CALIBRATING)) == AXIS_OBS_FAULT);
CHECK(latch_idle, AXIS_STATUS_STATE(AXIS_STATUS_ON_FAULT(AXIS_OBS_IDLE)) == AXIS_OBS_FAULT);
CHECK(latch_aligning, AXIS_STATUS_STATE(AXIS_STATUS_ON_FAULT(AXIS_OBS_ALIGNING)) == AXIS_OBS_FAULT);
CHECK(latch_running, AXIS_STATUS_STATE(AXIS_STATUS_ON_FAULT(AXIS_OBS_RUNNING)) == AXIS_OBS_FAULT);
CHECK(latch_fault, AXIS_STATUS_STATE(AXIS_STATUS_ON_FAULT(AXIS_OBS_FAULT)) == AXIS_OBS_FAULT);
CHECK(no_resume_after_fault, AXIS_STATUS_STATE(AXIS_STATUS_NEXT(
    AXIS_STATUS_ON_FAULT(0U), 1U, 0U, 0U)) == AXIS_OBS_FAULT);
CHECK(no_idle_after_fault, AXIS_STATUS_STATE(AXIS_STATUS_NEXT(
    AXIS_STATUS_ON_FAULT(0U), 0U, 0U, 0U)) == AXIS_OBS_FAULT);
CHECK(latch_preserves_reasons, AXIS_STATUS_INHIBITS(AXIS_STATUS_ON_FAULT(
    AXIS_STATUS_PACK(AXIS_OBS_IDLE, AXIS_INHIBIT_SPEED | AXIS_INHIBIT_ADC_FRAME))) ==
    (AXIS_INHIBIT_SPEED | AXIS_INHIBIT_ADC_FRAME | AXIS_INHIBIT_FAULT));
CHECK(recovered_reasons_clear, AXIS_STATUS_INHIBITS(AXIS_STATUS_NEXT(
    AXIS_STATUS_PACK(AXIS_OBS_IDLE, AXIS_INHIBIT_SPEED), 0U, 1U, 0U)) == 0U);
CHECK(combined_reasons, AXIS_STATUS_INHIBITS(AXIS_STATUS_NEXT(0U,0U,0U,0x17fU)) == 0x17fU);
CHECK(state_not_in_reasons, AXIS_STATUS_INHIBITS(AXIS_STATUS_PACK(AXIS_OBS_RUNNING, 0x100U)) == 0x100U);
